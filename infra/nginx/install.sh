#!/bin/bash
#=============================================================================
# Nginx Install Script
#
#   MODULES / EXTRA_CONFIG
#
#   Inject ENV:ZAP_PATH ZAPCTL APPS_DIR PKG_PATH APP_PATH
#   APP_ID APP_NAME APP_VERSION BUILD_PATH CPU_NUM [MAJOR_VERSION MINOR_VERSION]
#   ZLIB_VERSION   / PCRE2_VERSION  default 1.3.1 / 10.48
#   MODSEC_LIB_TARBALL / MODSEC_CONNECTOR_TARBALL / MODSEC_CRS_TARBALL
#        =  modsecurity/
#=============================================================================
set -euo pipefail

source "${ZAP_PATH}/scripts/zap/bash_utils.sh"

# ── Vars ────────────────────────────────────────────────────────────
NGINX_MIRROR="${NGINX_MIRROR:-$(pkg_mirror)}"
ZLIB_VERSION="${ZLIB_VERSION:-1.3.1}"
PCRE2_VERSION="${PCRE2_VERSION:-10.48}"
OPENSSL_VERSION="${OPENSSL_VERSION:-3.5.6}"
# ModSecurity (WAF; set MODSECURITY=true)
MODSEC_VERSION="${MODSEC_VERSION:-3.0.16}"
MODSEC_CONNECTOR_VERSION="${MODSEC_CONNECTOR_VERSION:-1.0.4}"
MODSEC_CRS_VERSION="${MODSEC_CRS_VERSION:-4.29.0}"
MODSEC_PREFIX="${MODSEC_PREFIX:-/usr/local/modsecurity}"

MODSEC_WAF_CONF="/etc/zap/nginx/modsecurity"
case "$(echo "${MODSECURITY:-false}" | tr '[:upper:]' '[:lower:]')" in
    true | 1 | yes | on) WAF_ENABLED=1 ;;
    *) WAF_ENABLED=0 ;;
esac

INSTALL_PATH="${APPS_DIR}/nginx"
NGINX_SRC="nginx-${APP_VERSION}"
ZLIB_SRC="zlib-${ZLIB_VERSION}"
PCRE2_SRC="pcre2-${PCRE2_VERSION}"
OPENSSL_SRC="openssl-${OPENSSL_VERSION}"
# ModSecurity: modsecurity/
MODSEC_LIB_PKG="${MODSEC_LIB_TARBALL:-modsecurity-v${MODSEC_VERSION}.tar.gz}"
MODSEC_CONN_PKG="${MODSEC_CONNECTOR_TARBALL:-ModSecurity-nginx-v${MODSEC_CONNECTOR_VERSION}.tar.gz}"
MODSEC_CRS_PKG="${MODSEC_CRS_TARBALL:-coreruleset-${MODSEC_CRS_VERSION}-minimal.tar.gz}"

# ── default user: www ─────────────────────────────────────
prepare_install_env www

# BUILD_PATH=runs/<run_id>/build
# run_id is generated by zapexec, and is a random string of 8 characters.
if [[ "${BUILD_PATH}" != "${ZAP_PATH}/data/appstore/runs/"*"/build" ]]; then
    log_error "Abnormal BUILD_PATH (${BUILD_PATH}); refusing to clean up"
    exit 1
fi
rm -rf "${BUILD_PATH}"
ensure_dir "${BUILD_PATH}" "${APP_PATH}"
cd "${PKG_PATH}"

# ── Download dependency sources (exit on failure) ─────────────────────────────────────────────
log_info "Downloading/verifying dependency sources ..."
if [ ! -f "${NGINX_SRC}.tar.gz" ]; then
    log_info "download nginx-${APP_VERSION}"
    fetch_file "${NGINX_MIRROR}/nginx/${NGINX_SRC}.tar.gz" "${NGINX_SRC}.tar.gz" || exit 1
fi
if [ ! -f "${ZLIB_SRC}.tar.gz" ]; then
    log_info "download ${ZLIB_SRC}"
    fetch_file "${NGINX_MIRROR}/zlib/${ZLIB_SRC}.tar.gz" "${ZLIB_SRC}.tar.gz" || exit 1
fi
if [ ! -f "${PCRE2_SRC}.tar.gz" ]; then
    log_info "download ${PCRE2_SRC}"
    fetch_file "${NGINX_MIRROR}/pcre2/${PCRE2_SRC}.tar.gz" "${PCRE2_SRC}.tar.gz" || exit 1
fi
if [ ! -f "${OPENSSL_SRC}.tar.gz" ]; then
    log_info "download ${OPENSSL_SRC}"
    fetch_file "${NGINX_MIRROR}/openssl/${OPENSSL_SRC}.tar.gz" "${OPENSSL_SRC}.tar.gz" || exit 1
fi

# ── Extract nginx / zlib / pcre2 ─────────────────────────────────────────────
log_info "Extracting source tarballs ..."
tar -xzf "${ZLIB_SRC}.tar.gz" -C "${BUILD_PATH}"
tar -xzf "${NGINX_SRC}.tar.gz" -C "${BUILD_PATH}"
tar -xzf "${PCRE2_SRC}.tar.gz" -C "${BUILD_PATH}"
tar -xzf "${OPENSSL_SRC}.tar.gz" -C "${BUILD_PATH}"

# ── Clean up old install leftovers ───────────────────────────────────────────────────
# New layout: install directly into ${APPS_DIR}/nginx (no version in the path). Compatible with
# the old "versioned directory + symlink" leftovers, which are cleaned up during upgrade to
# avoid appstore scanning duplicate nginx records.
if [ -d "${INSTALL_PATH}" ]; then
    log_warn "Detected existing ${INSTALL_PATH}; will back up conf and reinstall"
    if [ -d "${INSTALL_PATH}/conf" ]; then
        ensure_dir /root/zap_bak/nginx
        cp -Rf "${INSTALL_PATH}/conf" "/root/zap_bak/nginx/conf.$(date +%Y%m%d%H%M%S)" || true
    fi
    rm -rf "${INSTALL_PATH}"
fi
# Legacy leftover: the real nginx-<version> directory (once symlinked from ${APPS_DIR}/nginx)
if [ -e "${APPS_DIR}/nginx-${APP_VERSION}" ] && [ "${APPS_DIR}/nginx-${APP_VERSION}" != "${INSTALL_PATH}" ]; then
    log_warn "Cleaning up legacy versioned directory ${APPS_DIR}/nginx-${APP_VERSION}"
    rm -rf "${APPS_DIR}/nginx-${APP_VERSION}"
fi

# ── ModSecurity install deps  ──────────────────────────────────
install_modsec_deps() {
    local pm common="" p rc=0
    pm="$(pkg_manager)" || {
        log_warn "No package manager detected (${OS_NAME:-unknown}); skipping ModSecurity build dependency installation"
        return 1
    }
    case "${pm}" in
    apt)
        apt-get update -qq >/dev/null 2>&1 || true
        common="libtool autoconf automake g++ make pkg-config flex bison libxml2-dev libyajl-dev"
        ;;
    dnf | yum)
        common="libtool autoconf automake gcc-c++ make pkgconfig flex bison libxml2-devel yajl-devel"
        ;;
    apk)
        common="build-base autoconf automake libtool flex bison pkgconf libxml2-dev yajl-dev"
        ;;
    zypper)
        common="libtool autoconf automake gcc-c++ make pkg-config flex bison libxml2-devel yajl-devel"
        ;;
    esac

    log_info "${pm} Install ModSecurity build dependencies .."
    # 不吞输出：装包要几分钟，静默会让面板日志看起来像卡死
    case "${pm}" in
    apt) DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends ${common} 2>&1 ;;
    apk) apk add --no-cache ${common} 2>&1 ;;
    *) "${pm}" install -y ${common} 2>&1 ;;
    esac || {
        log_warn "Batch installation failed, please reinstall item by item .."
        for p in ${common}; do
            pkg_install_any "${pm}" "${p}" || rc=1
        done
    }

    # The packages most prone to rename across versions: offer candidates, any one installed is fine
    #   pcre : modsecurity 3.x only recognizes pcre2 (pcre3 lacks pcre2.h → fatal compile error),
    #          so pcre2 is preferred; pcre3 is only a fallback for old systems
    #   curl : the deb family has three implementation packages (openssl/gnutls/generic) with different names
    #   geoip: optional dependency (GeoIP support); the old package is removed on new systems → failure is not fatal
    case "${pm}" in
    apt)
        pkg_install_any "${pm}" libpcre2-dev libpcre3-dev || rc=1
        pkg_install_any "${pm}" libcurl4-openssl-dev libcurl4-gnutls-dev libcurl-dev || rc=1
        pkg_install_any "${pm}" libgeoip-dev libmaxminddb-dev || true
        ;;
    dnf | yum)
        pkg_install_any "${pm}" pcre2-devel pcre-devel || rc=1
        pkg_install_any "${pm}" libcurl-devel || rc=1
        pkg_install_any "${pm}" GeoIP-devel libmaxminddb-devel || true
        ;;
    apk)
        pkg_install_any "${pm}" pcre2-dev pcre-dev || rc=1
        pkg_install_any "${pm}" curl-dev || rc=1
        ;;
    zypper)
        pkg_install_any "${pm}" pcre2-devel pcre-devel || rc=1
        pkg_install_any "${pm}" libcurl-devel || rc=1
        ;;
    esac

    if [ "${rc}" -eq 0 ]; then
        log_ok "ModSecurity build dependencies ready"
    else
        log_warn "Some build dependencies were not installed; if libmodsecurity fails to compile due to missing headers/libs, install them manually"
    fi
    return "${rc}"
}

# ── pcre2: a hard dependency of libmodsecurity ────────────────────────────────────────
# modsecurity 3.x always does #include <pcre2.h>; the pcre3 dev package lacks this header,
# so compiling transaction.cc fails with a fatal error. Prefer the system dev package; if the
# system has none (offline mirror / old distro), build pcre2 from the source tree in build/ ——
# it is exactly the source tree nginx uses for --with-pcre, so versions match by construction.
# --disable-shared + --with-pic links it statically into libmodsecurity.so, so at runtime there
# is no extra dependency on the system libpcre2.
# Note: the result is returned via a global variable; **do not** write OPT="$(modsec_pcre2_option)" ——
# log_info prints to stdout, and command substitution would swallow the log (with its timestamp)
# into the variable, so configure would receive "[2026-09-26 ..." as the build system type and
# config.sub would error out immediately.
modsec_pcre2_option() {   # sets MODSEC_PCRE2_OPT (empty when pcre2 already present on the system); returns 1 on failure
    MODSEC_PCRE2_OPT=""
    if [ -f /usr/include/pcre2.h ] || [ -f /usr/local/include/pcre2.h ] \
        || pkg-config --exists libpcre2-8 2>/dev/null; then
        return 0
    fi
    local src="${BUILD_PATH}/${PCRE2_SRC}" stage="${BUILD_PATH}/pcre2-stage"
    log_info "System lacks pcre2 headers; building a copy from ${PCRE2_SRC} source for libmodsecurity ..."
    if [ ! -f "${stage}/include/pcre2.h" ]; then
        ( cd "${src}" &&
            ./configure --prefix="${stage}" --disable-shared --with-pic >/dev/null 2>&1 &&
            make -j "${CPU_NUM:-$(cpu_count)}" >/dev/null 2>&1 &&
            make install >/dev/null 2>&1 ) || {
            log_error "pcre2 source build failed; libmodsecurity cannot continue without pcre2.h"
            return 1
        }
    fi
    MODSEC_PCRE2_OPT="--with-pcre2=${stage}"
    return 0
}

# ── ModSecurity (WAF, optional): rule engine + nginx connector ───────────────────────
# Dynamic modules can only be added at compile time: nginx must be built with --with-compat,
# otherwise the module signature won't match and load_module is rejected. An already-installed
# nginx cannot add it later, so this is the only window.
if [ "${WAF_ENABLED}" = "1" ]; then
    log_info "Install option: building ModSecurity (WAF) support ..."
    # 1) Build dependencies: install per distro (apt / dnf / yum / apk / zypper); warn only if incomplete
    install_modsec_deps || true
    # 2) libmodsecurity (rule engine): like pcre2, fetched from the download mirror by a fixed
    #    package name, not from GitHub
    cd "${PKG_PATH}"
    if [ ! -f "${MODSEC_LIB_PKG}" ]; then
        log_info "download ${MODSEC_LIB_PKG}"
        fetch_file "${NGINX_MIRROR}/modsecurity/${MODSEC_LIB_PKG}" "${MODSEC_LIB_PKG}" || {
            log_error "libmodsecurity source download failed; aborting (disable this option to install plain nginx)"
            exit 1
        }
    fi
    # libmodsecurity hard-depends on pcre2: resolve it first (system package → source fallback);
    # if unavailable, don't waste minutes compiling and abort directly
    if ! modsec_pcre2_option; then
        log_error "libmodsecurity requires pcre2; install libpcre2-dev (deb) / pcre2-devel (rpm)"
        exit 1
    fi
    # The top-level directory name varies by package (libmodsecurity-vX / ModSecurity-vX …);
    # read it from the archive instead of guessing.
    # Do not use `tar -tzf x | head -1`: the archive has 6000+ entries / 500KB; head exits after
    # one line and tar writing to the pipe gets SIGPIPE, which under pipefail makes the whole
    # pipeline return 141 and set -e kills the install outright.
    # Use sed instead (it doesn't exit early, letting tar finish); on failure there is still a
    # readable message.
    MODSEC_SRC="$(tar -tzf "${MODSEC_LIB_PKG}" | sed -n '1{s|/.*||;p;}')"
    if [ -z "${MODSEC_SRC}" ]; then
        log_error "Cannot read the top-level directory name from ${MODSEC_LIB_PKG} (corrupt archive?)"
        exit 1
    fi
    tar -xzf "${MODSEC_LIB_PKG}" -C "${BUILD_PATH}"
    (
        cd "${BUILD_PATH}/${MODSEC_SRC}" &&
            ./build.sh &&
            ./configure --prefix="${MODSEC_PREFIX}" --without-lmdb ${MODSEC_PCRE2_OPT} &&
            make -j "${CPU_NUM:-$(cpu_count)}" &&
            make install
    ) || {
        log_error "libmodsecurity build failed; aborting"
        exit 1
    }
    # nginx relies on ldconfig to find libmodsecurity.so.3 at startup
    echo "${MODSEC_PREFIX}/lib" >/etc/ld.so.conf.d/zap-modsecurity.conf
    if [ -d "${MODSEC_PREFIX}/lib64" ]; then
        echo "${MODSEC_PREFIX}/lib64" >>/etc/ld.so.conf.d/zap-modsecurity.conf
    fi
    ldconfig || true
  
    if ! have_lib 'libmodsecurity.so.*' \
        && ! ls "${MODSEC_PREFIX}"/lib/libmodsecurity.so* >/dev/null 2>&1; then
        log_error "libmodsecurity not installed into ${MODSEC_PREFIX}/lib; aborting"
        exit 1
    fi
    # 3) ModSecurity-nginx connector (dynamic module source)
    if [ ! -f "${MODSEC_CONN_PKG}" ]; then
        log_info "download ${MODSEC_CONN_PKG}"
        fetch_file "${NGINX_MIRROR}/modsecurity/${MODSEC_CONN_PKG}" "${MODSEC_CONN_PKG}" || {
            log_error "ModSecurity-nginx connector download failed; aborting"
            exit 1
        }
    fi
    MODSEC_CONNECTOR_DIR="${BUILD_PATH}/ModSecurity-nginx"
    mkdir -p "${MODSEC_CONNECTOR_DIR}"
    tar -xzf "${MODSEC_CONN_PKG}" -C "${MODSEC_CONNECTOR_DIR}" --strip-components=1
    log_ok "libmodsecurity ${MODSEC_VERSION} and connector are ready"
fi

# ── configure: ─────────────────────────────────────────────
log_info "start build nginx-${APP_VERSION}(OpenSSL ${OPENSSL_VERSION}) ..."
cd "${BUILD_PATH}/${NGINX_SRC}"

configure_args=(
    --user=www
    --group=www
    --prefix="${INSTALL_PATH}"
    --pid-path=/var/run/nginx.pid
    --error-log-path=/var/log/nginx/error.log
    --http-log-path=/var/log/nginx/access.log
    # http general
    --with-http_ssl_module
    --with-http_v2_module
    --with-http_realip_module
    --with-http_addition_module
    --with-http_sub_module
    --with-http_dav_module
    --with-http_flv_module
    --with-http_mp4_module
    --with-http_gunzip_module
    --with-http_gzip_static_module
    --with-http_auth_request_module
    --with-http_random_index_module
    --with-http_secure_link_module
    --with-http_slice_module
    --with-http_stub_status_module
    # stream support
    --with-threads
    --with-file-aio
    # stream (TCP/UDP reverse proxy) + ssl/ssl_preread/realip/slice
    --with-stream
    --with-stream_ssl_module
    --with-stream_ssl_preread_module
    --with-stream_realip_module
    # deps: zlib / pcre2 / openssl
    --with-pcre="${BUILD_PATH}/${PCRE2_SRC}"
    --with-zlib="${BUILD_PATH}/${ZLIB_SRC}"
    --with-openssl="${BUILD_PATH}/${OPENSSL_SRC}"
    --with-openssl-opt=no-async
)

#  MODULES / EXTRA_CONFIG
if [ -n "${EXTRA_CONFIG:-}" ]; then
    read -r -a extra_args <<< "${EXTRA_CONFIG}"
    configure_args+=("${extra_args[@]}")
fi
if [ -n "${MODULES:-}" ]; then
    read -r -a module_args <<< "${MODULES}"
    configure_args+=("${module_args[@]}")
fi


if [ "${WAF_ENABLED}" = "1" ]; then
    configure_args+=(--with-compat --add-dynamic-module="${MODSEC_CONNECTOR_DIR}")
fi

log_info "configure ..."
./configure "${configure_args[@]}"
log_ok "configure done; starting make (parallel ${CPU_NUM:-auto})"
make -j "${CPU_NUM:-$(cpu_count)}"
make install
if [ ! -x "${INSTALL_PATH}/sbin/nginx" ]; then
    log_error "make install did not produce the nginx binary; installation failed"
    exit 1
fi
log_ok "nginx build & install complete: ${INSTALL_PATH}"

# ── mkdir conf.d / generate dhparam ────────────────────────────────────────
ensure_dir "${INSTALL_PATH}/conf/conf.d" /var/log/nginx

if [ ! -f "${INSTALL_PATH}/conf/dhparam.pem" ]; then
    log_info "Generating dhparam.pem (2048, may take a few seconds)..."
    openssl dhparam -out "${INSTALL_PATH}/conf/dhparam.pem" 2048 || true
fi

cp -f "${ZAP_PATH}/scripts/zap/conf/nginx.conf" "${INSTALL_PATH}/conf/nginx.conf"

if [ ! -f "${INSTALL_PATH}/conf/mime.types" ] && [ -f "${BUILD_PATH}/${NGINX_SRC}/conf/mime.types" ]; then
    cp -f "${BUILD_PATH}/${NGINX_SRC}/conf/mime.types" "${INSTALL_PATH}/conf/mime.types"
fi

# ── ModSecurity: deploy OWASP CRS and enable (default: log only, no blocking) ─────
if [ "${WAF_ENABLED}" = "1" ]; then
    log_info "Deploying OWASP CRS ruleset ..."
    ensure_dir "${MODSEC_WAF_CONF}"
    cd "${PKG_PATH}"
    if [ ! -f "${MODSEC_CRS_PKG}" ]; then
        log_info "download ${MODSEC_CRS_PKG}"
        fetch_file "${NGINX_MIRROR}/modsecurity/${MODSEC_CRS_PKG}" "${MODSEC_CRS_PKG}" || {
            log_error "OWASP CRS download failed; aborting"
            exit 1
        }
    fi
    ensure_dir "${MODSEC_WAF_CONF}/rules"
    tar -xzf "${MODSEC_CRS_PKG}" -C "${MODSEC_WAF_CONF}" --strip-components=1
    if [ ! -f "${MODSEC_WAF_CONF}/crs-setup.conf" ] && [ -f "${MODSEC_WAF_CONF}/crs-setup.conf.example" ]; then
        cp -f "${MODSEC_WAF_CONF}/crs-setup.conf.example" "${MODSEC_WAF_CONF}/crs-setup.conf"
    fi

    # Write Includes MODSEC_WAF_CONF   /etc/zap/nginx/modsecurity/
    {
        echo "# Generated By ZAP : ModSecurity Config (OWASP CRS ${MODSEC_CRS_VERSION})"
        echo "SecRuleEngine DetectionOnly"
        echo "SecRequestBodyAccess On"
        echo "SecAuditEngine RelevantOnly"
        echo 'SecAuditLogRelevantStatus "^(?:5|4(?!04))"'
        echo "SecAuditLogParts ABIJDEFHZ"
        echo "SecAuditLogType Serial"
        echo "SecAuditLog /var/log/modsec_audit.log"
        if [ -f "${MODSEC_WAF_CONF}/crs-setup.conf" ]; then
            echo "Include ${MODSEC_WAF_CONF}/crs-setup.conf"
        fi
        if [ -d "${MODSEC_WAF_CONF}/rules" ]; then
            echo "Include ${MODSEC_WAF_CONF}/rules/*.conf"
        fi
    } >"${MODSEC_WAF_CONF}/modsecurity.conf"

    # http-context directives go in a separate file (the main config already includes conf.d/*.conf), leaving the template untouched
    cat >"${INSTALL_PATH}/conf/conf.d/modsecurity.conf" <<EOF
# zap-generated: WAF enabled
modsecurity on;
modsecurity_rules_file ${MODSEC_WAF_CONF}/modsecurity.conf;
EOF

    # load_module must be at the very top of the outermost nginx.conf scope
    if ! grep -q "ngx_http_modsecurity_module.so" "${INSTALL_PATH}/conf/nginx.conf"; then
        sed -i "1i load_module modules/ngx_http_modsecurity_module.so;" "${INSTALL_PATH}/conf/nginx.conf"
    fi

    # Fallback: if WAF keeps nginx from starting, rip it out —— the nginx core must stay usable
    if ! "${INSTALL_PATH}/sbin/nginx" -t >/dev/null 2>&1; then
        log_error "WAF config failed nginx -t; removed WAF config (nginx still usable):"
        "${INSTALL_PATH}/sbin/nginx" -t || true
        rm -f "${INSTALL_PATH}/conf/conf.d/modsecurity.conf"
        sed -i "/ngx_http_modsecurity_module.so/d" "${INSTALL_PATH}/conf/nginx.conf"
    else
        log_ok "WAF ready: module loaded, engine DetectionOnly (audit log /var/log/modsec_audit.log)"
    fi
fi

# ── Install dir is ${APPS_DIR}/nginx
log_ok "nginx install dir: ${INSTALL_PATH}"

# ── Service (fix the hardcoded path in the template, generate per actual install dir) ────────
# Note: if sites were already configured, an extra nginx -t is needed; here we write the exact path.
# On start failure, print the "real cause" line by line into the log —— a bare "start failed"
# gives nothing to diagnose.
# Feed via <<< to read instead of a pipe: a pipe under pipefail invites SIGPIPE (141).
nginx_diag() {   # nginx_diag <title> <command...>
    local title="$1" out line
    shift
    out="$("$@" 2>&1)" || true
    log_error "${title}"
    while IFS= read -r line; do
        [ -n "${line}" ] && log_error "    ${line}"
    done <<<"${out}"
}

SVC_CMD=""
if command -v systemctl >/dev/null 2>&1; then
    log_info "Generating systemd service nginx.service (path: ${INSTALL_PATH})"
    cp -f "${PKG_PATH}/nginx.service" /etc/systemd/system/nginx.service
    chmod 644 /etc/systemd/system/nginx.service
    systemctl daemon-reload
    systemctl enable nginx.service >/dev/null 2>&1 || true
    if ! systemctl start nginx.service; then
        log_error "systemctl start nginx failed. Self-check output below (read in this order):"
        nginx_diag "① Config self-check (nginx -t):" "${INSTALL_PATH}/sbin/nginx" -t
        nginx_diag "② systemd status:" systemctl status nginx.service --no-pager -n 0
        nginx_diag "③ Last 15 log lines:" journalctl -u nginx.service --no-pager -n 15
    fi
    SVC_CMD="systemctl"
else
    log_warn "systemd not detected; trying 'service nginx start'"
    if command -v service >/dev/null 2>&1; then
        if ! service nginx start; then
            log_error "service nginx start failed:"
            nginx_diag "Config self-check (nginx -t):" "${INSTALL_PATH}/sbin/nginx" -t
        fi
        SVC_CMD="service"
    fi
fi
sleep 1

# ── Update zap app table (panel shows status / start-stop depends on info.yaml) ──────────────────
# info.yaml is written to APP_PATH (apps/<category>/<name>/) for zapexec discovery and start-stop
cat > "${APP_PATH}/info.yaml" <<YAML
svc_name: nginx
instance: nginx
install_dir: ${INSTALL_PATH}
version: ${APP_VERSION}
config_file: ${INSTALL_PATH}/conf/nginx.conf
config_files:
  - path: ${INSTALL_PATH}/conf/nginx.conf
    label: nginx.conf
  - path: ${INSTALL_PATH}/conf/fastcgi.conf
    label: fastcgi.conf
  - path: ${INSTALL_PATH}/conf/mime.types
    label: mime.types
pid_file: /var/run/nginx.pid
log_files:
  - /var/log/nginx/error.log
  - /var/log/nginx/access.log
expose: 
    tcp:80
    tcp:443
tags:
  - webserver
YAML

log_ok "nginx-${APP_VERSION} install complete (${INSTALL_PATH}); command: ${SVC_CMD:-none} start/stop/restart"
if [ -n "${SVC_CMD}" ] && command -v systemctl >/dev/null 2>&1; then
    if [ "$(systemctl is-active nginx.service)" != "active" ]; then
        log_warn "nginx service is not running yet: see the self-check output above; or run manually"
        log_warn "    ${INSTALL_PATH}/sbin/nginx -t"
        log_warn "    systemctl status nginx.service"
    fi
fi
